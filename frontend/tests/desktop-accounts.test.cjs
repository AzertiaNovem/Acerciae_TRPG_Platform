const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync(require.resolve('../src/lib/desktopAccounts.ts'), 'utf8');
const mod = {exports: {}};
new Function('module','exports', ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS, target:ts.ScriptTarget.ES2020}}).outputText)(mod, mod.exports);
test('desktop accounts survive restart, isolate servers and remove only the signed-out credential', async () => {
  const labels = new Map(), secrets = new Map();
  const storage = {getItem: k => labels.get(k) ?? null, setItem: (k,v) => labels.set(k,v)};
  const kc = {get: async k => secrets.get(k), set: async (k,v) => secrets.set(k,v), remove: async k => secrets.delete(k)};
  const start = () => mod.exports.createAccountDirectory(storage, async () => kc);
  const alice = {id:'same-id', username:'alice', display_name:'Alice'};
  const roster = start();
  await roster.remember('https://one.test', alice, 'first-secret');
  const first = roster.selected().slot;
  roster.select(null);
  assert.equal(await start().restore(), null);
  await roster.remember('https://two.test', alice, 'second-secret');
  const second = roster.selected().slot;
  assert.notEqual(first, second);
  assert.equal(JSON.stringify([...labels.values()]).includes('secret'), false);
  roster.select(first);
  assert.deepEqual(await start().restore(), {server:'https://one.test',token:'first-secret'});
  await roster.remember('https://one.test', alice, 'renewed-secret');
  assert.equal(roster.read().accounts.length, 2);
  assert.equal(roster.selected().slot, first);
  await roster.removeActive();
  assert.equal(secrets.has('account.' + first), false);
  roster.select(second);
  assert.equal((await start().restore()).token,'second-secret');
  const d = roster.read(); d.accounts[0].server = 'https://wrong.test';
  storage.setItem([...labels.keys()][0],JSON.stringify(d));
  await assert.rejects(start().restore(), /Invalid account/);
});
