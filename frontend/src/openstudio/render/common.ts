export interface RenderOptions {
  /** Show out-of-character chatter. */
  includeOoc: boolean;
  /** Show secret lines (type "secret", or spoken by a hidden/observer speaker). */
  includeSecret: boolean;
  /** Turns a project asset reference into a URL the document can load (null when unavailable). */
  assetUrl: (ref: string) => string | null;
  /** Document language (default "zh-CN"); also picks the built-in labels (Chinese for zh*, English otherwise). */
  lang?: string;
  /** Override any built-in label (e.g. with the app's translations). */
  labels?: Partial<RenderLabels>;
  /** IANA time zone used to show event times (default "UTC", like the server). */
  timeZone?: string;
}

