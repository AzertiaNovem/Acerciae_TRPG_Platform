export const isSecret = (e: LogEvent) => e.type === 'secret' || e.role === 'hidden';

/** Whether a line is shown: secret lines need includeSecret, OOC lines need includeOoc (a secret OOC line needs both). */
export function isVisible(e: LogEvent, includeOoc: boolean, includeSecret: boolean): boolean {
  if (isSecret(e) && !includeSecret) return false;
  if (e.type === 'ooc' && !includeOoc) return false;
  return true;
}

/** Speaker key → the character that plays it (the first sheet that lists the key). */
export function characterIndex(project: Project): Map<string, CharacterSheet> {
  const m = new Map<string, CharacterSheet>();
  for (const c of project.characters ?? []) for (const k of c.speakers ?? []) if (!m.has(k)) m.set(k, c);
  return m;
}

export const displayName = (e: LogEvent, chars: Map<string, CharacterSheet>) => chars.get(e.speaker_key)?.name || e.speaker_name;

/**
 * Characters for the cast list. A sheet whose speakers only ever say hidden lines is left out, so the cast does not
 * reveal who is behind the secret lines; a sheet with no lines at all (added by hand) is kept.
 */
export function visibleCast(project: Project, visible: LogEvent[]): CharacterSheet[] {
  const shown = new Set(visible.map((e) => e.speaker_key));
  const any = new Set((project.events ?? []).map((e) => e.speaker_key));
  return (project.characters ?? []).filter((c) => {
    const keys = c.speakers ?? [];
    if (keys.some((k) => shown.has(k))) return true;
    return !keys.some((k) => any.has(k));
  });
}

/**
 * Consistent speaker colours: one colour per character (or per unmapped speaker), assigned from the palette in the
 * order speakers first appear among the shown lines (call eventColor over the lines before characterColor).
 * A configured colour wins (looked up by speaker key, then character name); GM lines use gmColor when given.
 */
export function makeColors(
  chars: Map<string, CharacterSheet>,
  palette: readonly string[],
  configured: (key: string) => string | undefined,
  gmColor?: string,
) {
  const assigned = new Map<string, string>();
  const take = (identity: string) => {
    if (!assigned.has(identity)) assigned.set(identity, palette[assigned.size % palette.length]);
    return assigned.get(identity)!;
  };
  const characterColor = (c: CharacterSheet): string => {
    for (const k of [...(c.speakers ?? []), c.name]) { const v = configured(k); if (v) return v; }
    if (c.kind === 'gm' && gmColor) return gmColor;
    return take(`c:${c.name}`);
  };
  const eventColor = (e: LogEvent): string => {
    const c = chars.get(e.speaker_key);
    if (c) return characterColor(c);
    const v = configured(e.speaker_key);
    if (v) return v;
    if (e.role === 'gm' && gmColor) return gmColor;
    return take(`s:${e.speaker_key}`);
  };
  return { eventColor, characterColor };
}

export interface Section { key: string; title: string; events: LogEvent[] }

/** Consecutive runs of shown lines with the same scene_title. */
export function groupScenes(events: LogEvent[]): Section[] {
  const out: Section[] = [];
  for (const e of events) {
    const title = (e.scene_title ?? '').trim();
    const last = out[out.length - 1];
    if (!last || last.key !== title) out.push({ key: title, title, events: [e] });
    else last.events.push(e);
  }
  return out;
}

const pad = (n: number) => String(n).padStart(2, '0');

function parts(unix: number, timeZone: string): { y: string; mo: string; d: string; h: string; mi: string; s: string } | null {
  const date = new Date(unix * 1000);
  if (!Number.isFinite(date.getTime())) return null;
  if (timeZone !== 'UTC') {
    try {
      const f = new Intl.DateTimeFormat('en-CA', { timeZone, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' });
      const p: Record<string, string> = {};
      for (const x of f.formatToParts(date)) p[x.type] = x.value;
      return { y: p.year, mo: p.month, d: p.day, h: p.hour, mi: p.minute, s: p.second };
    } catch { /* unknown zone: fall back to UTC */ }
  }
  return { y: String(date.getUTCFullYear()), mo: pad(date.getUTCMonth() + 1), d: pad(date.getUTCDate()), h: pad(date.getUTCHours()), mi: pad(date.getUTCMinutes()), s: pad(date.getUTCSeconds()) };
}

/** The time shown next to a line: parsed time as HH:MM:SS (or with the date), else the time as written. */
export function timeLabel(e: LogEvent, timeZone: string, withDate: boolean): { text: string; full: string } {
  if (typeof e.time === 'number') {
    const p = parts(e.time, timeZone);
    if (p) {
      const full = `${p.y}-${p.mo}-${p.d} ${p.h}:${p.mi}:${p.s}`;
      return { text: withDate ? `${p.y}-${p.mo}-${p.d} ${p.h}:${p.mi}` : `${p.h}:${p.mi}:${p.s}`, full };
    }
  }
  const t = (e.time_text ?? '').trim();
  return { text: t, full: t };
}

/** "侦查 D100 = 45 · 成功"-style one-liner from structured dice, falling back to the raw roll text. */
export function diceSummary(d: DiceInfo): string {
  const bits: string[] = [];
  if (d.check_name) bits.push(d.check_name);
  let roll = d.expression ?? '';
  const rolls = Array.isArray(d.rolls) ? d.rolls.filter((n) => Number.isFinite(n)) : [];
  if (rolls.length > 1 || (rolls.length === 1 && rolls[0] !== d.total)) roll += ` [${rolls.join(', ')}]`;
  if (d.total !== null && d.total !== undefined && Number.isFinite(d.total)) roll += ` = ${d.total}`;
  if (roll.trim()) bits.push(roll.trim());
  const main = bits.join(' ');
  if (!main && !d.outcome) return (d.raw ?? '').trim();
  return d.outcome ? (main ? `${main} · ${d.outcome}` : d.outcome) : main;
}

/** success / failure / '' from the outcome text (Chinese and English dice-bot wording). */
export function outcomeClass(outcome: string): string {
  const o = outcome ?? '';
  if (/失败|fail|fumble|botch/i.test(o)) return 'fail';
  if (/成功|success|critical|crit/i.test(o)) return 'ok';
  return '';
}

export function visibleEvents(project: Project, includeOoc: boolean, includeSecret: boolean): LogEvent[] {
  return [...(project.events ?? [])].sort((a, b) => a.seq - b.seq).filter((e) => isVisible(e, includeOoc, includeSecret));
}

export const docTitle = (project: Project, l: RenderLabels) => (project.background?.title ?? '').trim() || (project.title ?? '').trim() || l.untitled;

/** Flattens a role card into label/value rows (scalars, arrays of scalars, one nested level), capped. */
export function roleCardRows(card: Record<string, unknown> | null, max = 40): [string, string][] {
  const rows: [string, string][] = [];
  const scalar = (v: unknown) => (typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean' ? String(v) : null);
  const add = (k: string, v: unknown, depth: number) => {
    if (rows.length >= max) return;
    const s = scalar(v);
    if (s !== null) { if (s.trim()) rows.push([k, s]); return; }
    if (Array.isArray(v)) {
      const items = v.map(scalar).filter((x): x is string => x !== null && x.trim() !== '');
      if (items.length) rows.push([k, items.join(', ')]);
      return;
    }
    if (v && typeof v === 'object' && depth < 1) for (const [k2, v2] of Object.entries(v as Record<string, unknown>)) add(`${k} · ${k2}`, v2, depth + 1);
  };
  if (card && typeof card === 'object') for (const [k, v] of Object.entries(card)) add(k, v, 0);
  return rows;
}
