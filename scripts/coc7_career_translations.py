#!/usr/bin/env python3
"""Builds backend/src/characters/Coc7CareersI18nData.cpp from scripts/coc7_careers_i18n/<lang>.json: the career names
and descriptions of backend/src/characters/Coc7CareersData.cpp (Simplified Chinese, from the community sheet) in the
other server languages (a missing language falls back to the Chinese). Each file maps the career id to {"name", "description"}. Usage: python3 scripts/coc7_career_translations.py"""
import json, os, re
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
langs = ['en', 'zh-TW', 'ja', 'ko', 'es', 'fr', 'de', 'ru', 'pt', 'it']
src = open(os.path.join(root, 'backend', 'src', 'characters', 'Coc7CareersData.cpp'), encoding='utf-8').read()
ids = [str(c['id']) for c in json.loads(re.search(r'R"~~\((.*)\)~~"', src, re.S).group(1))['careers']]
out = {i: {} for i in ids}
done = []
for lang in langs:
    f = os.path.join(root, 'scripts', 'coc7_careers_i18n', lang + '.json')
    if not os.path.exists(f): print('no', lang, 'translation: that language shows the sheet\'s Chinese'); continue
    done.append(lang)
    data = json.load(open(f, encoding='utf-8'))
    assert sorted(data, key=int) == sorted(ids, key=int), (lang, set(ids) ^ set(data))
    names = {}
    for i in ids:
        e = data[i]
        name, desc = e['name'].strip(), e['description'].strip()
        assert name and desc, (lang, i)
        assert name not in names, (lang, 'duplicate name', name, names.get(name), i)
        names[name] = i
        out[i][lang] = {'name': name, 'description': desc}
payload = json.dumps(out, ensure_ascii=False, separators=(',', ':'))
assert ')~~"' not in payload
path = os.path.join(root, 'backend', 'src', 'characters', 'Coc7CareersI18nData.cpp')
open(path, 'w', encoding='utf-8').write(
    '// Generated by scripts/coc7_career_translations.py from scripts/coc7_careers_i18n. Do not edit by hand.\n'
    '#include "Coc7Rules.h"\nnamespace acerciae::coc7 {\nconst char* kCareersI18nJson = R"~~(%s)~~";\n}\n' % payload)
print('wrote', path, len(payload), 'bytes,', len(ids), 'careers in', ', '.join(done))
