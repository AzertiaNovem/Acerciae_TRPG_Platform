#!/usr/bin/env python3
"""Builds backend/src/characters/Coc7CareersData.cpp from the community COC7 character sheet workbook
("COC7 CY23 Plus": sheets 职业列表 and 本职技能). Usage: python3 scripts/coc7_careers.py <workbook.xlsx>
Skill names stay Chinese here; the backend canonicalises them with the dice alias table at startup."""
import openpyxl, json, re, sys, os
wb=openpyxl.load_workbook(sys.argv[1], data_only=True)
lst=wb['职业列表']; mat=wb['本职技能']
# matrix: skill rows
rows=[(r, str(mat.cell(r,1).value).strip()) for r in range(3, mat.max_row+1) if mat.cell(r,1).value]
special={'☆','⊙','☯','※','任意特长'}
skillrows=[(r,n) for r,n in rows if n not in special and n!='自定义技能']
counts={n:r for r,n in rows if n in special}
cols=[(c, str(mat.cell(2,c).value).strip()) for c in range(3, mat.max_column+1) if mat.cell(2,c).value]
def fam(n):  # group header rows like '格斗：' and numbered variants '格斗①'
    m=re.match(r'^(.+?)[：:]\s*$', n)
    if m: return m.group(1), 'header'
    m=re.match(r'^(.+?)[①②③]$', n)
    if m: return m.group(1), 'slot'
    return n, 'plain'
careers=[]
anomalies=[]
# The matrix columns mirror the list rows in order; names repeat (艺术家 #13 and #208), so match by position and
# only use the name to confirm the alignment.
listrows=[]
for r in range(3, lst.max_row+1):
    b=lst.cell(r,2).value
    if not b: continue
    listrows.append({'name':str(b).strip(),'n':lst.cell(r,1).value,'cr':str(lst.cell(r,4).value or '').strip(),'attr':str(lst.cell(r,5).value or '').strip(),'desc':str(lst.cell(r,7).value or '').strip().replace('\n',' ')})
alias={'事务所侦探':'事务所侦探、保安','非熟练工人':'工人-非熟练工人','司法家':'司法科学家','赛车手/赛艇手':'赛车手/ 赛艇手'}
assert len(listrows)==len(cols), (len(listrows), len(cols))
for (c,cname),info in zip(cols,listrows):
    if alias.get(cname,cname)!=info['name']: anomalies.append(('misaligned',cname,info['name'])); continue
    fixed=[]; groups={}; freeN=0; spec=[]
    for r,n in skillrows:
        v=mat.cell(r,c).value
        if v in (None,''): continue
        v=str(v).strip(); base,kind=fam(n)
        if v=='★':
            if kind=='header': fixed.append({'skill':base,'any':True})
            elif kind=='slot':
                pass  # covered by header or by a text specialisation
            else: fixed.append({'skill':base})
            if kind=='slot' and not any(f['skill']==base for f in fixed): fixed.append({'skill':base,'any':True})
        elif v in ('☆','⊙','☯','※'):
            groups.setdefault(v, [])
            entry={'skill':base,'any':True} if kind!='plain' else {'skill':base}
            if entry not in groups[v]: groups[v].append(entry)
        else:
            # specialisation text, possibly carrying a group symbol e.g. '演☆'
            sym=None
            for s in '☆⊙☯※':
                if s in v: sym=s; v=v.replace(s,'').strip()
            entry={'skill':base,'spec':v}
            if sym: groups.setdefault(sym,[]).append(entry)
            else: fixed.append(entry)
    choice=[]
    for sym,members in groups.items():
        cnt=mat.cell(counts[sym],c).value
        try: cnt=int(cnt)
        except: cnt=1; anomalies.append(('no count',cname,sym))
        choice.append({'pick':cnt,'from':members})
    fv=mat.cell(counts['任意特长'],c).value
    try: freeN=int(fv) if fv not in (None,'') else 0
    except: anomalies.append(('bad free',cname,fv))
    # attribute formula → terms
    attrmap={'教育':'EDU','力量':'STR','敏捷':'DEX','外貌':'APP','意志':'POW','体质':'CON','体型':'SIZ','智力':'INT','幸运':'LUK'}
    terms=[]
    for part in re.split(r'[＋+]', info['attr']):
        part=part.strip()
        m=re.match(r'^(.+?)[×x\*](\d+)$', part)
        if not m: anomalies.append(('attr',cname,info['attr'])); continue
        names=[attrmap.get(x.strip()) for x in m.group(1).split('或')]
        if None in names: anomalies.append(('attrname',cname,part)); continue
        terms.append({'attrs':names,'mult':int(m.group(2))})
    cr=re.match(r'^(\d+)\s*-\s*(\d+)$', info['cr'])
    careers.append({'id':int(info['n']) if info['n'] is not None else len(careers)+1,'name':info['name'],'credit':[int(cr.group(1)),int(cr.group(2))] if cr else None,
                    'points':terms,'formula':info['attr'],'fixed':fixed,'choices':choice,'free':freeN,'description':info['desc']})
# The sheet repeats eleven names for later-sourcebook variants (艺术家 #13 and #208 differ): make names unique.
seen={}
for c in careers:
    n=seen.get(c['name'],0)+1; seen[c['name']]=n
    if n>1: c['name']=c['name']+'（'+'二三四五'[n-2]+'）'
for c in careers:
    for f in c['fixed']: f['skill']=f['skill'].replace(' Ω','').strip()
    for g in c['choices']:
        for m in g['from']: m['skill']=m['skill'].replace(' Ω','').strip()
payload=json.dumps({'source':os.path.basename(sys.argv[1]),'careers':careers}, ensure_ascii=False, separators=(',',':'))
assert ')~~"' not in payload
out=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','backend','src','characters','Coc7CareersData.cpp')
open(out,'w').write('// Generated by scripts/coc7_careers.py from %s. Do not edit by hand.\n#include "Coc7Rules.h"\nnamespace acerciae::coc7 {\nconst char* kCareersJson = R"~~(%s)~~";\n}\n' % (os.path.basename(sys.argv[1]), payload))
print('wrote', out, len(payload), 'bytes')
print('careers',len(careers),'anomalies',anomalies[:30])
import collections
print('skill names used:', sorted({f['skill'] for c in careers for f in c['fixed']} | {m['skill'] for c in careers for g in c['choices'] for m in g['from']}))
print('specs:', sorted({f.get('spec') for c in careers for f in c['fixed'] if f.get('spec')}))
print('examples:', json.dumps([c for c in careers if c['name'] in ('会计师','猎人','罪犯-独行罪犯','自定义职业','教授（原作向）')], ensure_ascii=False)[:3000])
